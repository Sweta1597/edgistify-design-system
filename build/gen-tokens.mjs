/* Emits the platform-neutral token layer from the authored CSS.
   ------------------------------------------------------------------
   The CSS stays the source: it carries the reasoning, and a generator
   that round-tripped it would throw every comment away. So the flow is
   one-way — CSS in, data out — and `lint:tokens-fresh` fails the build
   if the data on disk no longer matches the CSS.

   Two things happen here that a non-CSS platform cannot do for itself:

   1. var() is RESOLVED. React Native, Compose and SwiftUI have no
      custom properties; they need `#008277`, not `var(--ed-teal-600)`.
   2. The modes are PRE-COMPOSED. CSS gets dark+warehouse from the
      cascade — two attributes on <html>, four real states. A platform
      with no cascade needs the fourth state handed to it already
      merged, in the same order the contrast checker merges it.
   ------------------------------------------------------------------ */
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => readFileSync(new URL(`../dist/${f}`, import.meta.url), 'utf8');

/* Anchored on the previous block's closing brace: an unanchored match
   lets the composed dark+warehouse block leak into plain warehouse. */
function block(css, sel) {
  const re = new RegExp(`(^|\\})\\s*${sel}\\s*\\{([^}]*)\\}`, 'm');
  const m = css.match(re);
  return m ? m[2] : '';
}
function decls(body) {
  const out = {};
  for (const line of body.replace(/\/\*[\s\S]*?\*\//g, '').split(';')) {
    const m = line.match(/^\s*(--ed-[a-z0-9-]+)\s*:\s*(.+?)\s*$/i);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const prim = decls(block(read('primitives.css'), ':root'));
const sem  = read('semantic.css');
const base = decls(block(sem, ':root'));
const dark = decls(block(sem, '\\[data-theme="dark"\\]'));
const ware = decls(block(sem, '\\[data-mode="warehouse"\\]'));
const dkWh = decls(block(sem, '\\[data-theme="dark"\\]\\[data-mode="warehouse"\\]'));

/* Same composition order as build/contrast-check.mjs. If these two ever
   disagree, the numbers on the docs site stop describing the product. */
const MODES = {
  light:         { ...prim, ...base },
  dark:          { ...prim, ...base, ...dark },
  warehouse:     { ...prim, ...base, ...ware },
  darkWarehouse: { ...prim, ...base, ...dark, ...ware, ...dkWh },
};

/* Resolve var() to a concrete value, within the mode being emitted.
   A reference that cannot be resolved is a bug, not something to paper
   over with a fallback — token-lint already fails on undefined names,
   so anything unresolved here means the chain is circular. */
function resolve(value, table, name, seen = new Set()) {
  let v = String(value).trim();
  let guard = 0;
  while (v.includes('var(')) {
    if (guard++ > 20) throw new Error(`circular token reference at ${name}`);
    v = v.replace(/var\(\s*(--ed-[a-z0-9-]+)\s*(?:,\s*([^)]*))?\)/gi, (m, ref, fb) => {
      if (seen.has(ref)) throw new Error(`circular token reference: ${name} -> ${ref}`);
      if (table[ref] !== undefined) return table[ref];
      if (fb !== undefined) return fb.trim();
      throw new Error(`unresolved token ${ref} referenced by ${name}`);
    });
  }
  return v;
}

const out = {};
for (const [mode, table] of Object.entries(MODES)) {
  out[mode] = {};
  for (const [k, v] of Object.entries(table)) {
    out[mode][k.replace(/^--ed-/, '')] = resolve(v, table, k, new Set([k]));
  }
}

/* camelCase alongside the kebab names: `tokens.light.textMuted` is what a
   JS or Kotlin consumer will actually type. */
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

writeFileSync(new URL('../tokens/resolved.json', import.meta.url),
  JSON.stringify(out, null, 2) + '\n');

const js = `/* GENERATED by build/gen-tokens.mjs — do not edit.
   Every value is resolved and every mode pre-composed, so a platform with
   no cascade and no custom properties can use these directly. */
export const MODES = ${JSON.stringify(Object.keys(out))};

export const tokens = ${JSON.stringify(
  Object.fromEntries(Object.entries(out).map(([m, t]) =>
    [m, Object.fromEntries(Object.entries(t).map(([k, v]) => [camel(k), v]))])), null, 2)};

/** Light is the product. Dark and warehouse are added modes, never inherited. */
export function themeFor({ dark = false, warehouse = false } = {}) {
  if (dark && warehouse) return tokens.darkWarehouse;
  if (dark) return tokens.dark;
  if (warehouse) return tokens.warehouse;
  return tokens.light;
}
export default tokens;
`;
writeFileSync(new URL('../dist/tokens.js', import.meta.url), js);

const keys = Object.keys(out.light).map(camel);
writeFileSync(new URL('../dist/tokens.d.ts', import.meta.url),
`/* GENERATED by build/gen-tokens.mjs — do not edit. */
export type Mode = ${Object.keys(out).map((m) => `'${m}'`).join(' | ')};
export type TokenName = ${keys.map((k) => `'${k}'`).join('\n  | ')};
export type Theme = Record<TokenName, string>;
export declare const MODES: Mode[];
export declare const tokens: Record<Mode, Theme>;
export declare function themeFor(opts?: { dark?: boolean; warehouse?: boolean }): Theme;
export default tokens;
`);

console.log(`modes: ${Object.keys(out).join(', ')}`);
for (const [m, t] of Object.entries(out)) console.log(`  ${m.padEnd(14)} ${Object.keys(t).length} tokens`);
