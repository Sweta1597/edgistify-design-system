#!/usr/bin/env node
/* Mirrors the [data-theme="dark"] block onto prefers-color-scheme, guarded so an
   explicit data-theme="light" still wins. Optional: import it when an app should
   follow the OS theme (support docs). Apps with their own toggle don't need it. */
import { readFileSync, writeFileSync } from 'node:fs';
const css = readFileSync(new URL('../dist/semantic.css', import.meta.url), 'utf8');
const m = css.match(/\[data-theme="dark"\]\s*\{([\s\S]*?)\n\}/);
if (!m) { console.error('no dark block found'); process.exit(1); }
const body = m[1].split('\n').map(l => l ? '  ' + l : l).join('\n');
writeFileSync(new URL('../dist/dark-auto.css', import.meta.url),
`/* Generated by build/gen-dark-auto.mjs — do not edit.
 *
 * OPT-IN, AND NOT FOR THE PRODUCTS.
 *
 * Importing this makes an app follow the operating system's theme, which
 * contradicts the system's default: light is the product, dark is a mode the
 * user asks for. A seller opening the dashboard on a laptop set to dark would
 * get a dark dashboard they never chose.
 *
 * Use it only for reading surfaces where following the OS is the courteous
 * behaviour — the public support docs, a marketing page. Never in the seller
 * dashboard, the picker app or the admin.
 */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {${body}
  }
}
`);
console.log('wrote dist/dark-auto.css');
