#!/usr/bin/env node
/* Turns icons/svg into what the apps import, and keeps the manifest honest.

   Reads every file, then:
   - computes each icon's available sizes, whether filled equals outline
     (nothing to punch, so selection gets no fill change — the brief says
     to report these), and whether the accent paints first;
   - hashes the artwork. A changed hash bumps the icon's version and
     stamps the package version it changed in. A seed whose hash no
     longer matches its seedHash has been redrawn, so its status flips to
     `drawn` on its own;
   - writes icons/index.js and index.d.ts: one named export per icon,
     PascalCase, plus an ICONS map for config-driven lookups.

   CI regenerates and fails if anything differs, so a designer who drops
   files in without running `npm run build` gets told, with a diff.      */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  SIZES, STATES, SVG_DIR, ICONS_DIR, FILE_RE, readManifest, writeManifest, listSvgFiles,
  parseSvg, normaliseD, hashArt, packageVersion, pascal,
} from './icons-lib.mjs';

const manifest = readManifest();
const pkg = packageVersion();
const art = new Map();

for (const file of listSvgFiles()) {
  const m = FILE_RE.exec(file);
  if (!m) continue;
  const [, name, state, size] = m;
  const { paths } = parseSvg(readFileSync(join(SVG_DIR, file), 'utf8'));
  const body = paths.find((p) => p.attrs.class === 'body');
  const accent = paths.find((p) => p.attrs.class === 'accent');
  if (!body || !accent) continue;              // the lint reports it
  if (!art.has(name)) art.set(name, { outline: {}, filled: {}, first: paths[0].attrs.class });
  art.get(name)[state][size] = { body: normaliseD(body.attrs.d), accent: normaliseD(accent.attrs.d) };
}

const bumps = [], flips = [], identical = [], missing = [];
for (const ic of manifest.icons) {
  const a = art.get(ic.name);
  if (!a) { missing.push(ic.name); continue; }
  ic.sizes = SIZES.filter((s) => a.outline[s] && a.filled[s]);
  ic.fillIdentical = Object.fromEntries(ic.sizes.map((s) =>
    [s, a.outline[s].body === a.filled[s].body && a.outline[s].accent === a.filled[s].accent]));
  ic.accentFirst = a.first === 'accent';

  const hash = hashArt(a);
  ic.since ??= pkg;
  if (ic.hash === undefined) { ic.version = 1; ic.updated = ic.since; }
  else if (ic.hash !== hash) { ic.version += 1; ic.updated = pkg; bumps.push(`${ic.name} v${ic.version - 1} → v${ic.version}`); }
  ic.hash = hash;

  /* A seed that no longer matches what was fetched has been redrawn. */
  if (ic.status === 'seed' && (!ic.seedHash || hash !== ic.seedHash)) { ic.status = 'drawn'; flips.push(ic.name); }
  if (Object.values(ic.fillIdentical).some(Boolean)) identical.push(ic.name);
}
writeManifest(manifest);

/* ---- index.js / index.d.ts -------------------------------------------- */
const sorted = [...manifest.icons].filter((ic) => art.has(ic.name)).sort((a, b) => a.name.localeCompare(b.name));
const names = new Map();
for (const ic of sorted) {
  const p = pascal(ic.name);
  if (names.has(p)) throw new Error(`export name collision: ${ic.name} and ${names.get(p)} both become ${p}`);
  names.set(p, ic.name);
}

const def = (ic) => {
  const a = art.get(ic.name);
  const pick = (state) => Object.fromEntries(ic.sizes.map((s) => [s, a[state][s]]));
  return { name: ic.name, accentFirst: ic.accentFirst, hasAccent: ic.hasAccent, outline: pick('outline'), filled: pick('filled') };
};

const js = `/* GENERATED by build/icons-build.mjs from icons/svg — do not edit.
   One export per icon. Each carries both fill states at every optical
   size that exists; react/Icon picks the drawing for the rendered size. */
${sorted.map((ic) => `export const ${pascal(ic.name)} = ${JSON.stringify(def(ic))};`).join('\n')}

export const ICONS = {
${sorted.map((ic) => `  '${ic.name}': ${pascal(ic.name)},`).join('\n')}
};

export const LIBRARY_VERSION = ${JSON.stringify(pkg)};
`;
writeFileSync(join(ICONS_DIR, 'index.js'), js);

const dts = `/* GENERATED by build/icons-build.mjs — do not edit. */
export type IconSize = 20 | 24 | 48;
export interface IconArt { body: string; accent: string }
export interface IconDef {
  name: IconName;
  /** Paint the accent under the body: a tick on a disc, not a disc on a tick. */
  accentFirst: boolean;
  /** False for glyphs with nowhere to put an accent: chevrons, x, plus. */
  hasAccent: boolean;
  outline: Partial<Record<IconSize, IconArt>>;
  filled: Partial<Record<IconSize, IconArt>>;
}
export type IconName =
  ${sorted.map((ic) => `| '${ic.name}'`).join('\n  ')};
${sorted.map((ic) => `export declare const ${pascal(ic.name)}: IconDef;`).join('\n')}
export declare const ICONS: Record<IconName, IconDef>;
export declare const LIBRARY_VERSION: string;
`;
writeFileSync(join(ICONS_DIR, 'index.d.ts'), dts);

/* ---- report ----------------------------------------------------------- */
const by = (st) => manifest.icons.filter((ic) => ic.status === st).length;
console.log(`icons: ${sorted.length} exported — ${by('seed')} seed, ${by('drawn')} drawn, ${by('approved')} approved`);
if (missing.length) console.log(`  no files: ${missing.join(', ')}`);
if (flips.length) console.log(`  now drawn: ${flips.join(', ')}`);
if (bumps.length) { console.log(`  version bumped (add a line to icons/CHANGELOG.md):`); for (const b of bumps) console.log(`    ${b}`); }
console.log(`  filled = outline (no counter to punch): ${identical.length ? identical.join(', ') : 'none'}`);
